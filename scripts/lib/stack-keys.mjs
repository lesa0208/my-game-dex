/**
 * Signing keys of its own for a local stack (M15 P1a hardening): the pilot, and its disposable
 * rehearsal twin.
 *
 * Every local stack the Supabase CLI (3.0.0) starts shares the same built-in credentials: one
 * ES256 signing key (kid b81269f1-…) for every access token, one HS256 JWT secret, one publishable
 * and one secret API key, and one pair of Storage S3 keys. They are public (they ship in the CLI),
 * so a development token or the development secret key would be accepted by the pilot's API.
 * A stack with its own keys gets, generated here once, from the operating system's random source:
 *
 *   supabase/signing_keys.json   its own ES256 private signing key (a JWK array, the format of
 *                                `supabase gen signing-key`): user sessions, and the anon and
 *                                service_role keys the CLI derives, are signed with it
 *   supabase/.env                its own HS256 JWT secret (still accepted for legacy tokens),
 *                                publishable key and secret key, read by every CLI call through
 *                                env(...) in its generated config
 *
 * Both are owner-only (mode 600), in the stack's git-ignored folder, written once and never
 * overwritten, and never printed. Storage's S3 protocol, whose keys the CLI can't change, is off.
 * The app doesn't use it.
 */
import { execFileSync } from "node:child_process";
import { generateKeyPairSync, randomBytes, randomUUID, createHash, timingSafeEqual } from "node:crypto";
import { chmodSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export const SIGNING_KEYS_FILE = "signing_keys.json";
export const ENV_FILE = ".env";
/** The variables the generated config reads (env(...)): never values. */
export const KEY_VARIABLES = Object.freeze({
  jwt_secret: "MGD_STACK_JWT_SECRET",
  publishable_key: "MGD_STACK_PUBLISHABLE_KEY",
  secret_key: "MGD_STACK_SECRET_KEY",
});

/** The [auth] lines a stack with its own keys gets. No value: each names a variable or a file. */
export const OWN_KEY_CONFIG_LINES = Object.freeze([
  `jwt_secret = "env(${KEY_VARIABLES.jwt_secret})"`,
  `publishable_key = "env(${KEY_VARIABLES.publishable_key})"`,
  `secret_key = "env(${KEY_VARIABLES.secret_key})"`,
  `signing_keys_path = "./${SIGNING_KEYS_FILE}"`,
]);

const token = (bytes) => randomBytes(bytes).toString("base64url");

/** Fresh, independent keys. Pure apart from the random source; nothing is written. */
export function generateStackKeys() {
  const { privateKey } = generateKeyPairSync("ec", { namedCurve: "P-256" });
  const jwk = privateKey.export({ format: "jwk" });
  const signing = [{ kty: jwk.kty, kid: randomUUID(), use: "sig", key_ops: ["sign", "verify"], alg: "ES256", ext: true, d: jwk.d, crv: jwk.crv, x: jwk.x, y: jwk.y }];
  const values = {
    [KEY_VARIABLES.jwt_secret]: token(48),
    [KEY_VARIABLES.publishable_key]: `sb_publishable_${token(24)}`,
    [KEY_VARIABLES.secret_key]: `sb_secret_${token(24)}`,
  };
  const env = `# Generated by scripts/lib/stack-keys.mjs. Private: never commit, copy or print.\n${Object.entries(values).map(([k, v]) => `${k}=${v}`).join("\n")}\n`;
  return { signing: `${JSON.stringify(signing, null, 2)}\n`, env };
}

/**
 * Makes sure a stack's own keys exist in `supabaseDir` and are well formed. With `create`, missing
 * keys are generated (both files, owner-only, never overwriting). Without it (a restart of the
 * pilot) they must already be there: regenerating them would invalidate every session and the
 * kid its marker records, so it is refused. One file without the other, or a file that is empty,
 * truncated or malformed, is always refused. Returns { state: "created" | "kept", kid }.
 */
export function ensureStackKeys(supabaseDir, { create, label = "this stack" }) {
  const files = [join(supabaseDir, SIGNING_KEYS_FILE), join(supabaseDir, ENV_FILE)];
  const present = files.map((file) => existsSync(file));
  if (present[0] && present[1]) return { state: "kept", kid: readStackKeys(supabaseDir, label).kids[0] };
  if (present[0] || present[1]) {
    throw new Error(`Refusing: ${label} has only one of its key files (${files[present[0] ? 0 : 1]}). Its keys are incomplete; restoring them is a separately authorized recovery (docs/architecture/catalog-pilot-m15.md).`);
  }
  if (!create) {
    throw new Error(`Refusing: ${label}'s own signing keys are missing (${supabaseDir}). It would start with the CLI's shared keys. Restoring them is a separately authorized recovery (docs/architecture/catalog-pilot-m15.md).`);
  }
  const keys = generateStackKeys();
  writeFileSync(files[0], keys.signing, { flag: "wx", mode: 0o600 });
  writeFileSync(files[1], keys.env, { flag: "wx", mode: 0o600 });
  for (const file of files) chmodSync(file, 0o600);
  return { state: "created", kid: readStackKeys(supabaseDir, label).kids[0] };
}

const SHAPES = Object.freeze({
  [KEY_VARIABLES.jwt_secret]: /^[\w-]{64,}$/,
  [KEY_VARIABLES.publishable_key]: /^sb_publishable_[\w-]{32,}$/,
  [KEY_VARIABLES.secret_key]: /^sb_secret_[\w-]{32,}$/,
});

/**
 * The values in a stack's key files, checked to be complete and well formed (an empty, truncated
 * or hand-edited file is refused, never used). For comparison only: never printed.
 */
export function readStackKeys(supabaseDir, label = "this stack") {
  const bad = (what) => new Error(`Refusing: ${label}'s key files are incomplete or malformed (${what}). Restoring them is a separately authorized recovery (docs/architecture/catalog-pilot-m15.md).`);
  const env = Object.fromEntries(
    readFileSync(join(supabaseDir, ENV_FILE), "utf8").split(/\r?\n/).filter((l) => /^[A-Z_]+=/.test(l)).map((l) => [l.slice(0, l.indexOf("=")), l.slice(l.indexOf("=") + 1)]),
  );
  for (const [name, shape] of Object.entries(SHAPES)) if (!shape.test(env[name] ?? "")) throw bad(`${ENV_FILE}: ${name}`);
  let signing;
  try {
    signing = JSON.parse(readFileSync(join(supabaseDir, SIGNING_KEYS_FILE), "utf8"));
  } catch {
    throw bad(SIGNING_KEYS_FILE);
  }
  const ok = Array.isArray(signing) && signing.length > 0 && signing.every((k) => k?.alg === "ES256" && k.kty === "EC" && k.crv === "P-256" && /^[0-9a-f-]{36}$/.test(k.kid ?? "") && k.d && k.x && k.y);
  if (!ok) throw bad(SIGNING_KEYS_FILE);
  return { env, kids: signing.map((k) => k.kid) };
}

/**
 * The environment for a Supabase CLI call: without any MGD_STACK_* key variable, so a value set in
 * the shell can never take the place of the stack's own .env.
 */
export function cliEnv(env = process.env) {
  const out = { ...env };
  for (const name of Object.values(KEY_VARIABLES)) delete out[name];
  return out;
}

/**
 * What a RUNNING stack actually uses (`supabase status` only repeats its config): its Auth
 * publishes exactly its own signing key, and its own secret key (from the key file, not from the
 * status) opens Auth's admin API. Read only. Retries while the gateway is still coming up.
 */
export async function runningKeyProblems(apiUrl, keys, { attempts = 30, wait = 1000 } = {}) {
  let last = "it didn't answer";
  for (let i = 0; i < attempts; i++) {
    try {
      const jwks = await fetch(`${apiUrl}/auth/v1/.well-known/jwks.json`, { signal: AbortSignal.timeout(5000) });
      const served = jwks.ok ? (await jwks.json()).keys?.map((k) => k.kid) ?? [] : null;
      const admin = await fetch(`${apiUrl}/auth/v1/admin/users?per_page=1`, { headers: { apikey: keys.env[KEY_VARIABLES.secret_key] }, signal: AbortSignal.timeout(5000) });
      await admin.body?.cancel();
      if (served === null || admin.status >= 500) throw new Error(`Auth answered ${jwks.status}/${admin.status}`);
      const problems = [];
      if (served.length !== keys.kids.length || !served.every((kid) => keys.kids.includes(kid))) problems.push("its Auth publishes signing keys other than its own");
      if (admin.status !== 200) problems.push(`its own secret key doesn't open its Auth admin API (${admin.status})`);
      return problems;
    } catch (error) {
      last = error.message;
      await new Promise((resolve) => setTimeout(resolve, wait));
    }
  }
  return [`its keys couldn't be checked: ${last}`];
}

/** runningKeyProblems for synchronous callers: run in a child process, the keys passed on stdin. */
export function runningKeyProblemsSync(apiUrl, keys) {
  const script = `import(${JSON.stringify(new URL(import.meta.url).href)}).then(async (m) => {
    const input = JSON.parse(require("node:fs").readFileSync(0, "utf8"));
    process.stdout.write(JSON.stringify(await m.runningKeyProblems(input.apiUrl, input.keys)));
  });`;
  try {
    const out = execFileSync(process.execPath, ["-e", script], { input: JSON.stringify({ apiUrl, keys }), encoding: "utf8", stdio: ["pipe", "pipe", "ignore"], timeout: 240000 });
    return JSON.parse(out);
  } catch (error) {
    return [`its keys couldn't be checked (${error.code ?? "the check failed"})`];
  }
}

const same = (a, b) => {
  const x = createHash("sha256").update(String(a)).digest();
  const y = createHash("sha256").update(String(b)).digest();
  return timingSafeEqual(x, y);
};
const kidOf = (jwt) => {
  try {
    return JSON.parse(Buffer.from(String(jwt).split(".")[0], "base64url").toString()).kid ?? null;
  } catch {
    return null;
  }
};

/**
 * Throws unless a running stack's status reports its own keys: the publishable and secret keys
 * (and the JWT secret, when the status shows it) are the ones in its key files, and the anon and
 * service_role keys are signed with its own signing key. So a stack whose key files were lost, or
 * whose CLI fell back to the shared keys, is refused before any tool uses it. Pure, for tests.
 */
export function ownKeyProblems(status, keys) {
  const problems = [];
  const want = keys.env;
  if (!same(status?.PUBLISHABLE_KEY, want[KEY_VARIABLES.publishable_key])) problems.push("its publishable key isn't its own");
  if (!same(status?.SECRET_KEY, want[KEY_VARIABLES.secret_key])) problems.push("its secret key isn't its own");
  if (status?.JWT_SECRET && !/^\*+$/.test(status.JWT_SECRET) && !same(status.JWT_SECRET, want[KEY_VARIABLES.jwt_secret])) problems.push("its JWT secret isn't its own");
  for (const name of ["ANON_KEY", "SERVICE_ROLE_KEY"]) {
    if (!keys.kids.includes(kidOf(status?.[name]))) problems.push(`its ${name.toLowerCase().replace("_key", "")} key isn't signed with its own signing key`);
  }
  return problems;
}
